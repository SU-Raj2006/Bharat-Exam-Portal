function sortExams(criteria) {
    let sorted = [...sarkariExamsData];
    if(criteria === 'name') {
        sorted.sort((a,b) => a.title.localeCompare(b.title));
    } else if(criteria === 'deadline') {
        sorted.sort((a,b) => new Date(a.lastDate) - new Date(b.lastDate));
    }
    renderMasterTable(sorted);
}


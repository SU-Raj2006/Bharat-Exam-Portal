function handleGlobalSearch(query) {
    const box = document.getElementById('searchSuggestions');
    if(!query.trim()) {
        box.classList.add('hidden');
        return;
    }
    const match = sarkariExamsData.filter(e => e.title.toLowerCase().includes(query.toLowerCase()) || e.board.toLowerCase().includes(query.toLowerCase()));
    if(match.length > 0) {
        let html = '';
        match.forEach(m => {
            html += `<div onclick="openExamDetailsModal('${m.id}'); document.getElementById('searchSuggestions').classList.add('hidden');" class="p-2.5 hover:bg-slate-100 dark:hover:bg-slate-800 cursor-pointer text-xs font-semibold text-slate-800 dark:text-slate-200">${m.title} <span class="text-[10px] text-slate-500 block">${m.board}</span></div>`;
        });
        box.innerHTML = html;
        box.classList.remove('hidden');
    } else {
        box.innerHTML = `<div class="p-2.5 text-xs text-slate-500">No matching exams found.</div>`;
        box.classList.remove('hidden');
    }
}


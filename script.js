let bookmarkedExamIds = JSON.parse(localStorage.getItem('bharat_bookmarks') || '[]');
let myApplications = JSON.parse(localStorage.getItem('bharat_applications') || '[]');

window.onload = function() {
    if(localStorage.getItem('bharat_theme') === 'dark') {
        document.documentElement.classList.add('dark');
        document.getElementById('darkModeIcon').className = "fa-solid fa-sun";
    }
    updateCounters();
    renderDashboardLists();
    renderMasterTable(sarkariExamsData);
    populateWizardDropdown();
};

function toggleDarkMode() {
    if(document.documentElement.classList.contains('dark')) {
        document.documentElement.classList.remove('dark');
        localStorage.setItem('bharat_theme', 'light');
        document.getElementById('darkModeIcon').className = "fa-solid fa-moon";
    } else {
        document.documentElement.classList.add('dark');
        localStorage.setItem('bharat_theme', 'dark');
        document.getElementById('darkModeIcon').className = "fa-solid fa-sun";
    }
}

function updateCounters() {
    document.getElementById('bookmarkCount').innerText = bookmarkedExamIds.length;
    document.getElementById('myAppsCount').innerText = myApplications.length;
}

function switchTab(tabId) {
    document.querySelectorAll('main > div').forEach(el => el.classList.add('hidden'));
    const targetView = document.getElementById('view-' + tabId);
    if(targetView) targetView.classList.remove('hidden');

    document.querySelectorAll('.nav-btn').forEach(btn => {
        btn.classList.remove('bg-red-600', 'text-white', 'shadow-md');
        btn.classList.add('text-slate-300', 'hover:text-white', 'hover:bg-slate-800');
    });
    const activeBtn = document.getElementById('nav-' + tabId);
    if(activeBtn) {
        activeBtn.classList.add('bg-red-600', 'text-white', 'shadow-md');
        activeBtn.classList.remove('text-slate-300', 'hover:text-white', 'hover:bg-slate-800');
    }

    if(tabId === 'tracker') {
        renderMyApplicationsTracker();
    }
    window.scrollTo({ top: 0, behavior: 'smooth' });
}


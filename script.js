function filterCategory(cat) {
    currentFilter = cat;
    document.querySelectorAll('.filter-chip').forEach(chip => {
        chip.classList.remove('bg-sarkariBlue', 'text-white');
        chip.classList.add('bg-white', 'dark:bg-slate-900', 'text-slate-700', 'dark:text-slate-200', 'border', 'border-slate-200', 'dark:border-slate-800');
    });
    event.target.classList.add('bg-sarkariBlue', 'text-white');
    event.target.classList.remove('bg-white', 'dark:bg-slate-900', 'text-slate-700', 'dark:text-slate-200', 'border', 'border-slate-200', 'dark:border-slate-800');

    if(cat === 'all') {
        renderMasterTable(sarkariExamsData);
    } else {
        const filtered = sarkariExamsData.filter(e => e.category === cat);
        renderMasterTable(filtered);
    }
}

function toggleBookmark(examId, event) {
    event.stopPropagation();
    if(bookmarkedExamIds.includes(examId)) {
        bookmarkedExamIds = bookmarkedExamIds.filter(id => id !== examId);
    } else {
        bookmarkedExamIds.push(examId);
    }
    localStorage.setItem('bharat_bookmarks', JSON.stringify(bookmarkedExamIds));
    updateCounters();
    renderDashboardLists();
    renderMasterTable(sarkariExamsData);
}

